import re

from doc_core import Raw, esc


def _norm(p):
    return re.sub(r"\{[^}]*\}", "{}", p)


def render(d, ctx):
    f = ctx["facts"]
    rc = ctx["rowcounts"]
    cm = ctx["clientmap"]
    d.h(1, "A", "Appendix A - Every HTTP route", anchor="app-a")
    d.p(
        f"{len(f['routes'])} method + path pairs, generated by importing <code>app.main</code> and walking <code>app.routes</code>. "
        "Gate: <i>public</i> = no login; <i>login</i> = any signed-in user; otherwise the feature keys / admin / wrapper "
        "dependencies. Demo guard = what the demo write guard does for the App Review login: <i>pass</i> (a read, or an "
        "allowlisted write - the route's own gate and the demo's features still apply) or <i>blocks</i> (403 DEMO_READ_ONLY)."
    )
    rows = []
    for r in sorted(f["routes"], key=lambda r: (r["path"], r["method"])):
        gate = ", ".join(r["gate"]).replace("feat:", "").replace("any:", "any of ") if r["gate"] else ("login" if r["login"] else "public")
        demo = "pass" if r["method"] in ("GET", "HEAD") or r["demo_allow"] else "blocks"
        rows.append([r["method"], Raw(f"<code>{esc(r['path'])}</code>"), gate, demo, Raw(f"<code>{esc(r['src'])}</code>")])
    d.table(["Method", "Path", "Gate", "Demo guard", "Source"], rows, widths=["7%", "43%", "18%", "8%", "24%"], cls="compact tiny")

    d.h(1, "B", "Appendix B - Every table and column", anchor="app-b")
    d.p(
        "Generated from the SQLAlchemy metadata (all model modules). PK = primary key, FK = real foreign key. Rows = "
        "read-only count from production on the day of writing (production at 0056)."
    )
    rows = []
    for t in f["tables"]:
        cols = []
        for c in t["columns"]:
            s = f"{c['name']}"
            tags = []
            if c["pk"]:
                tags.append("PK")
            if c["fk"]:
                tags.append("FK " + c["fk"][0])
            s = f"<b>{esc(s)}</b>" if c["pk"] else esc(s)
            s += f" <span class='muted'>{esc(c['type'].lower())}{(' ' + ' '.join(tags)) if tags else ''}</span>"
            cols.append(s)
        n = rc.get(t["name"])
        rows.append([Raw(f"<code>{esc(t['name'])}</code><br/><span class='muted'>{esc(t.get('module') or '')}.{esc(t.get('cls') or '')}</span>"), f"{n:,}" if isinstance(n, int) else "new", Raw(", ".join(cols))])
    d.table(["Table / model", "Rows", "Columns"], rows, widths=["22%", "8%", "70%"], cls="compact tiny")

    d.h(1, "C", "Appendix C - Migration chain", anchor="app-c")
    rows = [[a["rev"], a["down"], a["title"]] for a in f["alembic"]]
    d.table(["Revision", "Down revision", "Title (first docstring line)"], rows, widths=["11%", "13%", "76%"], cls="compact tiny")

    d.h(1, "D", "Appendix D - Client calls checked against the server", anchor="app-d")
    server = {(r["method"], _norm(r["path"])) for r in f["routes"]}
    used = {}
    for page, v in cm["web"].items():
        for e in v["endpoints"]:
            used.setdefault(e, set()).add("web " + page.replace("pages/", ""))
    for repo, eps in cm["repo_eps"].items():
        if repo.endswith("labels_repository.dart"):
            continue
        for e in eps:
            used.setdefault(e, set()).add("app " + repo.split("/")[-1].replace("_repository.dart", ""))
    missing = []
    for e in sorted(used):
        m, _, p = e.partition(" ")
        if m == "?":
            continue
        p = p.replace("/api/checklists/admin/definitions/{}/{}", "/api/checklists/admin/definitions/{}")
        if (m, _norm(p)) not in server and (m, _norm(p).rstrip("/")) not in server:
            missing.append([m, Raw(f"<code>{esc(p)}</code>"), ", ".join(sorted(used[e]))])
    unused = []
    used_norm = {(e.partition(" ")[0], _norm(e.partition(" ")[2])) for e in used}
    for r in sorted(f["routes"], key=lambda r: r["path"]):
        if (r["method"], _norm(r["path"])) not in used_norm and r["path"].startswith("/api/") and r["method"] != "HEAD":
            unused.append([r["method"], Raw(f"<code>{esc(r['path'])}</code>"), r["src"]])
    d.p(
        f"Every endpoint the website (api.js through its pages) and the app (repositories) call was matched against the "
        f"server's routes. <b>{len(used)}</b> distinct client calls; "
        + (f"<b>{len(missing)}</b> not matched by the static analysis (listed below - usually a path the analyser could not resolve, not a broken call)." if missing else "<b>every one matches a server route</b> (method and path).")
    )
    if missing:
        d.table(["Method", "Client path", "Called from"], missing, widths=["10%", "50%", "40%"], cls="compact tiny")
    d.p(
        f"Server routes no client page or repository references ({len(unused)}): kept for old app builds, used by "
        "the public checklist page, by scripts, or reached through a helper the analyser does not follow: file and "
        "image URLs used directly in links / img tags, CSV downloads, and the app's core calls outside repositories "
        "(<code>/api/health</code> connectivity ping, <code>/api/app/config</code> update gate, <code>/api/glossary</code>)."
    )
    d.table(["Method", "Path", "Source"], unused, widths=["10%", "55%", "35%"], cls="compact tiny")
