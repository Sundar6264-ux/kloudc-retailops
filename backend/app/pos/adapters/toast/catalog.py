"""Toast Menus API: the catalog (``/menus/v2/menus``), its change stamp
(``/menus/v2/metadata``) and the Toast-specific menu parsing.

Moved unchanged from ``services/inventory_api.py`` in multi-store M1 batch
MT2; every name below still works as ``inventory_api.<name>``. Toast rules
kept here:

- the "Toast E-Commerce Autogenerated" mirror and a test menu are skipped;
- catalog "Each" / "Container" variants (``catalogProductInfo.productVariant``)
  and " - Each" / " - Container" name pairs are paired;
- ``pricingStrategy`` SIZE_PRICE / OPEN_PRICE / MENU_SPECIFIC_PRICE and a $0
  price give no price (``menu_price``);
- the menu ``sku`` holds one barcode, merged with the CSV's ";"-list by
  ``merged_barcode`` (POS-neutral since MT3: ``app/pos/barcodes.py``; still
  importable from here).

MT3 adds ``catalog_snapshot`` / ``item_from_menu_info``: the parsed menu as
POS-neutral ``Item`` models (``CatalogSnapshot``). Building inventory rows from
them is POS-neutral (``app/pos/sync/catalog.py``).
"""

import datetime as dt
import re
from collections import defaultdict
from typing import Dict, List, Optional, Tuple

from app.pos.adapters.toast import client as _client
from app.pos.adapters.toast import timeparse as _timeparse
from app.pos.barcodes import _codes, merged_barcode  # noqa: F401 - moved to app/pos/barcodes.py (MT3)
from app.pos.models import Category, CatalogSnapshot, Item, to_decimal

MENUS_PATH = "/menus/v2/menus"
METADATA_PATH = "/menus/v2/metadata"

# Menus that are never inventory: Toast's own e-commerce mirror and a test
# menu. (A menu outside the CSV's category groups is left out anyway - see
# inventory_api `_included`.)
SKIP_MENUS = {"toast e-commerce autogenerated - do not edit", "test menu"}
CONTAINER_MENU = "container"
CONTAINER_OPTION = "container"


def fetch_menus() -> dict:
    data = _client.toast_get(MENUS_PATH, timeout=180.0)
    if not isinstance(data, dict) or "menus" not in data:
        raise _client.ToastFetchError("Unexpected /menus/v2/menus response")
    return data


def fetch_menu_last_updated() -> Optional[dt.datetime]:
    data = _client.toast_get(METADATA_PATH, timeout=30.0)
    return _timeparse.parse_toast_time((data or {}).get("lastUpdated"))


# ---------------------------------------------------------------------------
# Menu parsing
# ---------------------------------------------------------------------------


_VARIANT_SUFFIX = re.compile(r"\s+-\s+(each|container)\s*$", re.IGNORECASE)


class MenuItemInfo:
    __slots__ = ("guid", "item_name", "product_name", "option", "price", "prices", "pricing_strategy", "sku", "plu", "paths")

    def __init__(self, guid: str):
        self.guid = guid
        self.item_name = None
        self.product_name = None
        self.option = None  # "each" / "container" for a variant, else None
        self.price = None
        self.prices = set()
        self.pricing_strategy = None
        self.sku = None
        self.plu = None
        self.paths: List[Tuple[str, str, Optional[str]]] = []  # (menu, group, subgroup)

    @property
    def base_name(self) -> Optional[str]:
        """The menu name without a " - Each" / " - Container" suffix."""
        m = _VARIANT_SUFFIX.search(self.item_name or "")
        return self.item_name[: m.start()].rstrip() if m else self.item_name

    @property
    def name(self) -> Optional[str]:
        if not self.option:
            return self.item_name
        return self.product_name or self.base_name

    @property
    def is_container(self) -> bool:
        return self.option == CONTAINER_OPTION

    def placement(self) -> Optional[Tuple[str, str, Optional[str]]]:
        """Deepest non-Container menu path (first one on a tie)."""
        paths = [p for p in self.paths if p[0].strip().lower() != CONTAINER_MENU] or self.paths
        if not paths:
            return None
        return max(paths, key=lambda p: 1 if p[2] else 0)


def parse_menus(menus: dict) -> Dict[str, MenuItemInfo]:
    """guid -> MenuItemInfo, merging every place an item appears (an item
    can be in several menus / groups)."""
    out: Dict[str, MenuItemInfo] = {}

    def walk(groups, menu_name, path):
        for g in groups or []:
            gpath = path + [g.get("name") or ""]
            for it in g.get("menuItems") or []:
                guid = it.get("guid")
                if not guid:
                    continue
                info = out.get(guid)
                if info is None:
                    info = out[guid] = MenuItemInfo(guid)
                    info.item_name = (it.get("name") or "").strip() or None
                    cp = it.get("catalogProductInfo") or {}
                    info.product_name = ((cp.get("product") or {}).get("name") or "").strip() or None
                    for opt in (cp.get("productVariant") or {}).get("selectedOptions") or []:
                        value = ((opt or {}).get("value") or {}).get("name")
                        if value:
                            info.option = value.strip().lower()
                    info.pricing_strategy = it.get("pricingStrategy")
                    info.price = it.get("price")
                    info.sku = (it.get("sku") or "").strip() or None
                    info.plu = (it.get("plu") or "").strip() or None
                if it.get("price") is not None:
                    info.prices.add(round(float(it["price"]), 2))
                info.paths.append((menu_name, gpath[0], gpath[1] if len(gpath) > 1 else None))
            walk(g.get("menuGroups"), menu_name, gpath)

    for menu in menus.get("menus") or []:
        name = (menu.get("name") or "").strip()
        if name.lower() in SKIP_MENUS:
            continue
        walk(menu.get("menuGroups"), name, [])
    # Some Each/Container pairs have no catalog variant info, only the name
    # suffix: treat "X - Each" + "X - Container" as a pair too.
    by_base = defaultdict(list)
    for info in out.values():
        m = _VARIANT_SUFFIX.search(info.item_name or "")
        if m and not info.option:
            by_base[info.base_name.lower()].append((info, m.group(1).lower()))
    for pair in by_base.values():
        if len({kind for _, kind in pair}) > 1:
            for info, kind in pair:
                info.option = kind
    return out


def menu_price(info: MenuItemInfo) -> Optional[float]:
    if info.pricing_strategy in ("SIZE_PRICE", "OPEN_PRICE") or info.price is None:
        return None
    if float(info.price) == 0.0:
        return None  # the CSV leaves a $0 price blank (never 0.00)
    if info.pricing_strategy == "MENU_SPECIFIC_PRICE" and len(info.prices) > 1:
        return None
    return float(info.price)


# ---------------------------------------------------------------------------
# Menu -> Item (multi-store M1 batch MT3)
# ---------------------------------------------------------------------------


def item_from_menu_info(info: MenuItemInfo) -> Item:
    """One parsed menu item as an ``Item``:

    - ``name``: the catalog product name for an Each/Container variant, else
      the menu name (``MenuItemInfo.name``); ``other_names``: the menu name
      with and without its " - Each" / " - Container" suffix (an imported
      name that matches one of them is kept);
    - ``price``: ``menu_price`` (None for size/open pricing, $0, or a
      menu-specific price that differs between menus);
    - ``barcodes``: the menu ``sku`` (ONE barcode - see ``merged_barcode``);
    - ``category``: the deepest non-Container menu path; ``locations``: every
      (menu, group, subgroup) the item is listed under.
    """
    placement = info.placement()
    price = menu_price(info)
    return Item(
        external_id=info.guid,
        name=info.name,
        barcodes=(info.sku,) if info.sku else (),
        plu=info.plu,
        price=to_decimal(price) if price is not None else None,
        category=Category(*placement) if placement else None,
        locations=tuple(Category(menu, group, sub) for menu, group, sub in info.paths),
        other_names=(info.item_name, info.base_name),
        variant_kind=info.option,
        price_rule=info.pricing_strategy,
    )


def catalog_snapshot(menus: dict) -> CatalogSnapshot:
    """A /menus/v2/menus answer as a ``CatalogSnapshot`` (items in the order
    ``parse_menus`` first met them; ``changed_at`` = the menu's lastUpdated)."""
    menu = parse_menus(menus)
    return CatalogSnapshot(
        items=tuple(item_from_menu_info(info) for info in menu.values()),
        changed_at=_timeparse.parse_toast_time(menus.get("lastUpdated")),
    )
