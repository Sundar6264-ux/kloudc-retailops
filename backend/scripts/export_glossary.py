"""Write the app's bundled copy of the glossary (so it works offline and on
first launch) from app/glossary.py - the single source of truth.

Run after changing app/glossary.py or content/help/glossary.json:
    cd backend && .venv/bin/python scripts/export_glossary.py [--app-repo ../../storeops-app]
(scripts/help/sync_help_to_app.sh runs it with the help content.) Without
--app-repo the app is the storeops-app folder next to this repository, else
the older mobile/ layout. tests/test_ops_glossary.py fails if the bundled copy
is out of date.
"""

import json
import pathlib
import sys

BACKEND = pathlib.Path(__file__).resolve().parents[1]
sys.path.insert(0, str(BACKEND))

from app.glossary import get_glossary  # noqa: E402

GLOSSARY_DART = pathlib.Path("lib") / "core" / "glossary" / "glossary_data.dart"


def default_app_repo() -> pathlib.Path:
    for candidate in (BACKEND.parents[1] / "storeops-app", BACKEND.parents[1] / "mobile"):
        if (candidate / "pubspec.yaml").exists():
            return candidate
    return BACKEND.parents[1] / "mobile"


TARGET = default_app_repo() / GLOSSARY_DART
BEGIN = "// BEGIN GLOSSARY JSON"
END = "// END GLOSSARY JSON"


def render() -> str:
    body = json.dumps(get_glossary(), indent=1, ensure_ascii=False)
    assert "'''" not in body
    return (
        "// GENERATED by backend/scripts/export_glossary.py from\n"
        "// backend/app/glossary.py + content/help/glossary.json - do not edit by hand.\n"
        "// The app's bundled glossary (used offline / before /api/glossary loads).\n\n"
        f"{BEGIN}\n"
        f"const String kBundledGlossaryJson = r'''\n{body}\n''';\n"
        f"{END}\n"
    )


def bundled_json(text: str) -> dict:
    inner = text.split("r'''", 1)[1].rsplit("'''", 1)[0]
    return json.loads(inner)


if __name__ == "__main__":
    import argparse

    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--app-repo", default="", help="the Flutter app's folder (default: next to this repo)")
    args = ap.parse_args()
    target = (pathlib.Path(args.app_repo).resolve() / GLOSSARY_DART) if args.app_repo else TARGET
    target.parent.mkdir(parents=True, exist_ok=True)
    target.write_text(render(), encoding="utf-8")
    print(f"wrote {target}")
