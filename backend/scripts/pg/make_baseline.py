"""Generate the frozen PostgreSQL baseline of the store schema (platform
contract 11.1). Run ONCE, review, commit; never regenerate for a revision
other than the baseline's own.

    cd backend
    .venv/bin/python scripts/pg/make_baseline.py            # writes alembic/pg_baseline/
    .venv/bin/python scripts/pg/make_baseline.py --check    # exit 1 if the committed files differ

What it does:
1. Runs this checkout's SQLite migration chain up to the baseline revision
   (0062) twice, into two scratch files, a second apart.
2. Reflects the first file and writes `alembic/pg_baseline/<rev>.sql`: every
   table, column (types mapped to PostgreSQL), NOT NULL, normalised server
   default, primary key, unique and CHECK constraint and index, in the
   chain's own order and names.
3. Writes `alembic/pg_baseline/<rev>_seed.json`: the rows the chain itself
   inserts (teams, category overrides, checklist definitions, WhatsApp
   groups, ...). Cells that differ between the two runs are the migrations'
   own "now" and are stored as markers, filled at baseline time.

Type mapping: INTEGER -> integer (a single-column integer primary key ->
`GENERATED BY DEFAULT AS IDENTITY`: never reuses an id, like SQLite's
AUTOINCREMENT, and still takes explicit ids), VARCHAR[(n)] -> varchar[(n)],
TEXT -> text, DATETIME -> timestamptz (every DateTime in the models is
UTCDateTime), DATE -> date, BOOLEAN -> boolean, FLOAT -> double precision.

FOREIGN KEYs are deliberately NOT created. SQLite never enforced them (no
`PRAGMA foreign_keys=ON` anywhere): the app relies on that - e.g. deleting a
user keeps the done tasks and history rows that name them - and production
data holds such references. The models keep their ForeignKey()s (ORM joins,
documentation). Enforcing them is a separate decision (ON DELETE rules per
key + a data clean-up), see PLATFORM_CONTRACT.md "As built - A".
"""

from __future__ import annotations

import argparse
import datetime as dt
import json
import os
import pathlib
import re
import sqlite3
import subprocess
import sys
import tempfile
import time
from typing import Dict, List, Optional, Tuple

BACKEND = pathlib.Path(__file__).resolve().parents[2]
OUT_DIR = BACKEND / "alembic" / "pg_baseline"
BASELINE_REVISION = "0062"
NOW_MARK = "__now__"  # utcnow() at baseline time
NOW_SECONDS_MARK = "__now_seconds__"  # the same, whole seconds (CURRENT_TIMESTAMP-style)

PG_RESERVED = {
    "all", "analyse", "analyze", "and", "any", "array", "as", "asc", "asymmetric", "both", "case", "cast",
    "check", "collate", "column", "constraint", "create", "current_catalog", "current_date", "current_role",
    "current_time", "current_timestamp", "current_user", "default", "deferrable", "desc", "distinct", "do",
    "else", "end", "except", "false", "fetch", "for", "foreign", "from", "grant", "group", "having", "in",
    "initially", "intersect", "into", "lateral", "leading", "limit", "localtime", "localtimestamp", "not",
    "null", "offset", "on", "only", "or", "order", "placing", "primary", "references", "returning", "select",
    "session_user", "some", "symmetric", "system_user", "table", "then", "to", "trailing", "true", "union",
    "unique", "user", "using", "variadic", "when", "where", "window", "with", "authorization", "binary",
    "collation", "concurrently", "cross", "current_schema", "freeze", "full", "ilike", "inner", "is", "isnull",
    "join", "left", "like", "natural", "notnull", "outer", "overlaps", "right", "similar", "tablesample",
    "verbose", "key", "rank", "version", "day", "position", "value", "type", "name",
}


def q(name: str) -> str:
    """Quotes an identifier when PostgreSQL needs (or might need) it."""
    if re.fullmatch(r"[a-z_][a-z0-9_]*", name) and name not in PG_RESERVED:
        return name
    return '"' + name.replace('"', '""') + '"'


def run_chain(db_file: pathlib.Path, revision: str) -> None:
    env = dict(os.environ, DATABASE_URL=f"sqlite:///{db_file}")
    alembic = pathlib.Path(sys.executable).parent / "alembic"
    cmd = [str(alembic), "upgrade", revision] if alembic.exists() else [sys.executable, "-m", "alembic", "upgrade", revision]
    done = subprocess.run(cmd, cwd=str(BACKEND), env=env, capture_output=True, text=True)
    if done.returncode != 0:
        raise SystemExit(f"alembic upgrade {revision} failed:\n{done.stderr}")


# --- schema ---------------------------------------------------------------------


def pg_type(sqlite_type: str) -> str:
    t = sqlite_type.strip().upper()
    m = re.fullmatch(r"VARCHAR\((\d+)\)", t)
    if m:
        return f"VARCHAR({m.group(1)})"
    mapping = {
        "INTEGER": "INTEGER",
        "VARCHAR": "VARCHAR",
        "TEXT": "TEXT",
        "DATETIME": "TIMESTAMP WITH TIME ZONE",
        "DATE": "DATE",
        "BOOLEAN": "BOOLEAN",
        "FLOAT": "DOUBLE PRECISION",
    }
    if t not in mapping:
        raise SystemExit(f"no PostgreSQL mapping for SQLite type {sqlite_type!r}")
    return mapping[t]


def pg_default(sqlite_type: str, default: Optional[str]) -> Optional[str]:
    """Normalised server default: booleans true/false, numbers bare,
    strings kept as quoted literals."""
    if default is None:
        return None
    raw = default.strip()
    while raw.startswith("(") and raw.endswith(")"):
        raw = raw[1:-1].strip()
    t = sqlite_type.strip().upper()
    unquoted = raw[1:-1] if len(raw) >= 2 and raw[0] == raw[-1] == "'" else raw
    if t == "BOOLEAN":
        if unquoted in ("0", "false", "FALSE"):
            return "false"
        if unquoted in ("1", "true", "TRUE"):
            return "true"
        raise SystemExit(f"boolean default {default!r}")
    if t in ("INTEGER", "FLOAT"):
        if not re.fullmatch(r"-?\d+(\.\d+)?", unquoted):
            raise SystemExit(f"numeric default {default!r}")
        return unquoted
    if raw.upper() == "CURRENT_TIMESTAMP":
        return "CURRENT_TIMESTAMP"
    if not (raw.startswith("'") and raw.endswith("'")):
        raise SystemExit(f"text default {default!r} is not a quoted literal")
    return raw


def build_schema_sql(db_file: pathlib.Path) -> Tuple[str, List[str]]:
    from sqlalchemy import create_engine, inspect

    engine = create_engine(f"sqlite:///{db_file}")
    insp = inspect(engine)
    con = sqlite3.connect(str(db_file))
    statements: List[str] = []
    tables: List[str] = []
    try:
        # Creation order of the chain (sqlite_master rowid order).
        names = [
            r[0]
            for r in con.execute(
                "SELECT name FROM sqlite_master WHERE type = 'table' AND name NOT LIKE 'sqlite_%' ORDER BY rowid"
            )
        ]
        for table in names:
            if table == "alembic_version":
                continue
            tables.append(table)
            pragma = {r[1]: r for r in con.execute(f'PRAGMA table_info("{table}")')}
            pk_cols = insp.get_pk_constraint(table)["constrained_columns"]
            lines = []
            for col in insp.get_columns(table):
                name = col["name"]
                stype = pragma[name][2]
                ctype = pg_type(stype)
                identity = len(pk_cols) == 1 and pk_cols[0] == name and ctype == "INTEGER"
                parts = [q(name), ctype]
                if identity:
                    parts.append("GENERATED BY DEFAULT AS IDENTITY")
                default = pg_default(stype, pragma[name][4])
                if default is not None:
                    parts.append(f"DEFAULT {default}")
                if not col["nullable"] or name in pk_cols:
                    parts.append("NOT NULL")
                lines.append("    " + " ".join(parts))
            lines.append(f"    CONSTRAINT {q(table + '_pkey')} PRIMARY KEY ({', '.join(q(c) for c in pk_cols)})")
            for uq in insp.get_unique_constraints(table):
                cols = uq["column_names"]
                name = uq.get("name") or f"{table}_{'_'.join(cols)}_key"
                lines.append(f"    CONSTRAINT {q(name)} UNIQUE ({', '.join(q(c) for c in cols)})")
            for ck in insp.get_check_constraints(table):
                sqltext = ck["sqltext"].strip()
                if ck.get("name"):
                    lines.append(f"    CONSTRAINT {q(ck['name'])} CHECK ({sqltext})")
                else:
                    lines.append(f"    CHECK ({sqltext})")
            statements.append(f"CREATE TABLE {q(table)} (\n" + ",\n".join(lines) + "\n);")
            for ix in sorted(insp.get_indexes(table), key=lambda i: i["name"]):
                if ix.get("dialect_options") or None in ix["column_names"]:
                    raise SystemExit(f"index {ix['name']} needs a hand-written PostgreSQL form: {ix}")
                unique = "UNIQUE " if ix["unique"] else ""
                cols = ", ".join(q(c) for c in ix["column_names"])
                statements.append(f"CREATE {unique}INDEX {q(ix['name'])} ON {q(table)} ({cols});")
    finally:
        con.close()
        engine.dispose()
    return "\n\n".join(statements) + "\n", tables


# --- seed rows ---------------------------------------------------------------------


def _rows(db_file: pathlib.Path) -> Dict[str, Tuple[List[str], List[tuple]]]:
    con = sqlite3.connect(str(db_file))
    try:
        out = {}
        names = [
            r[0]
            for r in con.execute(
                "SELECT name FROM sqlite_master WHERE type = 'table' AND name NOT LIKE 'sqlite_%' ORDER BY rowid"
            )
        ]
        for table in names:
            if table == "alembic_version":
                continue
            cols = [r[1] for r in con.execute(f'PRAGMA table_info("{table}")')]
            rows = con.execute(f'SELECT * FROM "{table}" ORDER BY rowid').fetchall()
            if rows:
                types = {r[1]: r[2].upper() for r in con.execute(f'PRAGMA table_info("{table}")')}
                out[table] = (cols, rows, types)
        return out
    finally:
        con.close()


def _is_db_time(value) -> bool:
    return isinstance(value, str) and bool(re.fullmatch(r"\d{4}-\d\d-\d\d \d\d:\d\d:\d\d(\.\d{6})?", value))


def build_seed(first: pathlib.Path, second: pathlib.Path) -> Dict:
    a, b = _rows(first), _rows(second)
    if set(a) != set(b):
        raise SystemExit(f"seeded tables differ between runs: {sorted(set(a) ^ set(b))}")
    seed = {"revision": BASELINE_REVISION, "tables": []}
    for table, (cols, rows, types) in a.items():
        rows_b = b[table][1]
        if len(rows) != len(rows_b):
            raise SystemExit(f"{table}: row count differs between runs")
        out_rows = []
        for ra, rb in zip(rows, rows_b):
            row = {}
            for col, va, vb in zip(cols, ra, rb):
                kind = types[col]
                if va != vb:
                    if not (kind == "DATETIME" and _is_db_time(va) and _is_db_time(vb)):
                        raise SystemExit(f"{table}.{col} differs between runs and is not a timestamp: {va!r} / {vb!r}")
                    row[col] = NOW_SECONDS_MARK if va.endswith(".000000") and vb.endswith(".000000") else NOW_MARK
                    continue
                if va is not None and kind == "BOOLEAN":
                    va = bool(va)
                elif va is not None and kind == "DATETIME":
                    if not _is_db_time(va):
                        raise SystemExit(f"{table}.{col}: unexpected timestamp text {va!r}")
                row[col] = va
            out_rows.append(row)
        seed["tables"].append({"table": table, "columns": cols, "rows": out_rows})
    return seed


HEADER = """-- KloudC RetailOps store schema, PostgreSQL baseline at Alembic revision {rev}.
-- GENERATED by backend/scripts/pg/make_baseline.py from the SQLite migration
-- chain 0001-{rev}, reviewed and frozen (platform contract 11.1). Do not edit:
-- schema changes go in a new migration (0063+) that runs on SQLite AND
-- PostgreSQL. alembic/env.py runs this file (then {rev}_seed.json) on an empty
-- PostgreSQL database and stamps {rev}.
--
-- Differences from the SQLite chain, on purpose:
-- * no FOREIGN KEY constraints (SQLite never enforced them; see the script's
--   docstring);
-- * single-column integer primary keys are IDENTITY columns (never reuse ids,
--   like SQLite AUTOINCREMENT);
-- * timestamps are timestamptz (UTC), floats double precision, boolean
--   defaults true/false.
-- Statements are separated by a blank line (env.py splits on it).

"""


def generate() -> Tuple[str, str]:
    with tempfile.TemporaryDirectory(prefix="so_a_baseline_") as tmp:
        first, second = pathlib.Path(tmp) / "a.db", pathlib.Path(tmp) / "b.db"
        run_chain(first, BASELINE_REVISION)
        time.sleep(1.2)
        run_chain(second, BASELINE_REVISION)
        sql, _tables = build_schema_sql(first)
        seed = build_seed(first, second)
    return HEADER.format(rev=BASELINE_REVISION) + sql, json.dumps(seed, indent=1, ensure_ascii=False) + "\n"


def main(argv: Optional[List[str]] = None) -> int:
    p = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    p.add_argument("--check", action="store_true", help="Compare with the committed files instead of writing")
    args = p.parse_args(argv)
    sql, seed = generate()
    sql_path = OUT_DIR / f"{BASELINE_REVISION}.sql"
    seed_path = OUT_DIR / f"{BASELINE_REVISION}_seed.json"
    if args.check:
        ok = sql_path.read_text() == sql and seed_path.read_text() == seed
        print("baseline files match the chain" if ok else "baseline files DIFFER from the chain")
        return 0 if ok else 1
    OUT_DIR.mkdir(parents=True, exist_ok=True)
    sql_path.write_text(sql)
    seed_path.write_text(seed)
    print(f"wrote {sql_path} and {seed_path} ({dt.datetime.now().isoformat(timespec='seconds')})")
    return 0


if __name__ == "__main__":
    sys.exit(main())
